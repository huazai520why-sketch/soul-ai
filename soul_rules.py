def hard_hit(t):
    """命中内容红线 → 返回命中的那个词；未命中 / 空串 → None。纯函数、可单测。"""
    s = str(t or "")
    if not s:
        return None
    for b in HARD_BAN:
        if b in s:
            return b
    return None


def invite_hit(t):
    """命中「我主动约见面」形态 → 返回命中的原文片段；未命中 / 空串 → None。纯函数、可单测。

    ⭐ 2026-10-07：与 `hard_hit` 同级，供 `soul_daemon.gate()` 做**代码级硬闸**
    （铁律「见面必须她主导，绝不自己约」不能只写在提示词里 —— 本地层看不到提示词）。
    """
    s = str(t or "")
    if not s:
        return None
    m = _INVITE_RE.search(s)
    return m.group(0) if m else None


