# 虚词/高频字：统计它们没有意义（「的」「了」会出现在每一条里）。
# 后两行是实盘踩出来的噪声：「天」来自"明天/几天"、「一」来自"一晚/一趟"——
# 这类时间量词/数词几乎每条消息都有，当话题词会**误报**。
_STOP = set("的了是我在有和就都很也要去个没这那你我他好不啊哦嗯呢吧嘛哈行对说"
            "天时侯候会能还又才真太最什么点些上下里来回做过"
            "一二三四五六七八九十百千万两几多少半"
            "早夜晚今明昨年月日周点钟分")


def _anchors():
    """当前实例的城市锚点词（双开：实例0 重庆 / 实例>0 沈阳）；失败回退实例0。"""
    try:
        from soul_persona import anchors as _a
        return _a()
    except Exception:
        return _ANCHOR_FALLBACK


def stuck_words(t):
    """话题词 = 2-gram + 单个实词字（去掉虚词与锚点字）。

    ⚠️ 只取 2-gram 会漏单字话题（实测「蛋」在「四个蛋」「鸡蛋」里都是单字出现）；
    ⚠️ 单字必须**同时**滤掉锚点字：本函数会把「重庆」拆出「重」「庆」，
       只排除双字词 → 实测「重」×3、「庆」×3 照样误报死磕。
    """
    A = _anchors()
    ACH = set("".join(A))
    out = []
    for seg in re.findall(r"[\u4e00-\u9fa5]+", str(t)):
        for i in range(len(seg) - 1):
            two = seg[i:i + 2]
            # ⭐ 2026-10-06 收紧：**两字都是虚词**的 2-gram 直接丢。
            #   原实现只给「单字」滤虚词，2-gram 无条件保留 → 实测误报：
            #   三句话都以「的了」收尾时，`的了`×3 被当成话题词。
            #   为什么现在必须修：本检测器已从「发送侧只 print 一嗓子」升级成
            #   **写进提示词的准硬约束**——误报的代价从「多看一行日志」变成
            #   「模型被逼着绕开常用字」。所以宁可收紧。
            #   ⚠️ 必须是「**两字都**虚词」才丢：只丢一个会误伤「上班」「明天」这类正常话题词
            #      （「上」在 STOP 里，但「上班」是真话题）。
            if two[0] in _STOP and two[1] in _STOP:
                continue
            out.append(two)
        for ch in seg:
            if ch not in _STOP and ch not in ACH:
                out.append(ch)
    return set(out)


def stuck_hot(texts, min_hits=3):
    """在 `texts` 里找「在 ≥min_hits **条**里都出现」的话题词。

    返回 [(词, 出现条数)]，按条数降序、同频优先双字（「鸡蛋」×3 比「蛋」×3 直观）；无 → []。
    ⚠️ 锚点词（重庆/小面…）**整体排除**：零锚点 30 人是长期欠账，转向时本来就要反复给
       城市细节，把「重庆」当死磕会误伤补锚点策略。
    """
    from collections import Counter
    pool = [str(t) for t in (texts or []) if str(t or "").strip()]
    if len(pool) < min_hits:
        return []
    cnt = Counter()
    for t in pool:
        for w in stuck_words(t):
            cnt[w] += 1
    A = _anchors()
    hot = [(w, n) for w, n in cnt.items() if n >= min_hits and w not in A]
    # 频次降序 → **同频长词优先**（「鸡蛋」排在「蛋」前）：禁令要按信息量最大的那个词给，
    # 否则「鸡」「蛋」这类被长词覆盖的单字会把禁区撑得莫名其妙地宽。
    hot.sort(key=lambda x: (-x[1], -len(x[0])))
    return hot


def stuck_line(texts, min_hits=3):
    """**生成侧**用：把「我最近说过的几句」变成一行提示词；没死磕 → ''（fail-open）。

    例：
      【⚠️ 死磕警报·脚本实测，本轮必须执行】
      我在最近 3 条里反复提到 「鸡蛋」×3 —— 同一个由头已经聊了 3 轮。
      本轮**必须换话题**（或拐到我这边的一件具体小事）；上面这些词**一个都不许再出现**。
    """
    try:
        hot = stuck_hot(texts, min_hits=min_hits)
        if not hot:
            return ""
        pool = [str(t) for t in (texts or []) if str(t or "").strip()]
        # ⭐ 只留**互不覆盖**的词：`hot` 已经同频长词优先，所以先来的更具体。
        #   实测产物：hot=[鸡蛋/鸡/蛋] → 只列「鸡蛋」（否则等于禁了「鸡」「蛋」两个常用字，
        #   模型被逼得比必要的更紧，反而写不出自然的话）。
        picked = []
        for w, n in hot:
            if any((w in p) or (p in w) for p, _ in picked):
                continue
            picked.append((w, n))
            if len(picked) >= 3:
                break
        detail = "、".join("「%s」×%d" % (w, n) for w, n in picked)
        return ("【⚠️ 死磕警报·脚本实测，本轮必须执行】\n"
                "我在最近 %d 条里反复提到 %s —— 同一个由头已经聊了 %d 轮。\n"
                "本轮**必须换话题**（或拐到我这边的一件具体小事）；"
                "上面这些词**一个都不许再出现**。\n"
                % (len(pool), detail, len(pool)))
    except Exception:
        return ""
